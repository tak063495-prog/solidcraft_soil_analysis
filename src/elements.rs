//! Isoparametric Tet4/Tet10 and Tri3/Tri6 integration.
//! Tet10 ordering: vertices 0..3, edges 01,12,20,03,13,23 (VTK).
use crate::{Error, Result, elastic};
use nalgebra::{DMatrix, Matrix3, SMatrix, SVector, Vector3};
use serde::{Deserialize, Serialize};
use std::sync::OnceLock;

pub const EDGES: [[usize; 2]; 6] = [[0, 1], [1, 2], [2, 0], [0, 3], [1, 3], [2, 3]];
pub const FACES: [[usize; 3]; 4] = [[1, 2, 3], [0, 3, 2], [0, 1, 3], [0, 2, 1]];

#[derive(Debug, Clone)]
pub struct VolumePoint {
    pub natural: [f64; 3],
    pub position: [f64; 3],
    pub weight_m3: f64,
    pub shape: Vec<f64>,
    pub b: DMatrix<f64>,
}
#[derive(Debug, Clone)]
pub struct FacePoint {
    pub position: [f64; 3],
    /// Outward area vector including the reference quadrature weight.
    pub area_vector: [f64; 3],
    pub shape: Vec<f64>,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct PointInfo {
    pub element_index: usize,
    pub local_index: usize,
    pub natural_coordinates: [f64; 3],
    pub position_m: [f64; 3],
    pub weight_m3: f64,
    pub shape_functions: Vec<f64>,
}

/// Gauss-Jacobi on [0,1] with weight (1-x)^alpha, generated by its
/// orthonormal three-term recurrence, not copied quadrature tables.
fn gauss(n: usize, alpha: f64) -> Vec<(f64, f64)> {
    let mut j = DMatrix::zeros(n, n);
    for k in 0..n {
        let t = 2. * k as f64 + alpha;
        j[(k, k)] = if t == 0. {
            0.
        } else {
            -alpha * alpha / (t * (t + 2.))
        };
        if k > 0 {
            let kf = k as f64;
            let off = 2. / t * (kf * kf * (kf + alpha).powi(2) / ((t - 1.) * (t + 1.))).sqrt();
            j[(k, k - 1)] = off;
            j[(k - 1, k)] = off;
        }
    }
    let eig = j.symmetric_eigen();
    let mut result: Vec<_> = (0..n)
        .map(|k| {
            (
                (eig.eigenvalues[k] + 1.) / 2.,
                eig.eigenvectors[(0, k)].powi(2) / (alpha + 1.),
            )
        })
        .collect();
    result.sort_by(|a, b| a.0.total_cmp(&b.0));
    result
}
fn make_volume_rule(order: usize) -> Vec<([f64; 3], f64)> {
    let a = gauss(order, 2.);
    let b = gauss(order, 1.);
    let c = gauss(order, 0.);
    let mut result = Vec::new();
    for &(u, wu) in &a {
        for &(v, wv) in &b {
            for &(w, ww) in &c {
                result.push(([u, (1. - u) * v, (1. - u) * (1. - v) * w], wu * wv * ww));
            }
        }
    }
    result
}
pub fn volume_rule(order: usize) -> Result<&'static [([f64; 3], f64)]> {
    static Q3: OnceLock<Vec<([f64; 3], f64)>> = OnceLock::new();
    static Q4: OnceLock<Vec<([f64; 3], f64)>> = OnceLock::new();
    static Q5: OnceLock<Vec<([f64; 3], f64)>> = OnceLock::new();
    let cache = match order {
        3 => &Q3,
        4 => &Q4,
        5 => &Q5,
        _ => {
            return Err(Error::Input(
                "Tet10 quadrature order must be 3, 4 or 5".into(),
            ));
        }
    };
    Ok(cache.get_or_init(|| make_volume_rule(order)))
}

pub fn tet10_shape(r: [f64; 3]) -> ([f64; 10], [[f64; 3]; 10]) {
    let l = [1. - r.iter().sum::<f64>(), r[0], r[1], r[2]];
    let g = [[-1., -1., -1.], [1., 0., 0.], [0., 1., 0.], [0., 0., 1.]];
    let mut shape = [0.; 10];
    let mut gradient = [[0.; 3]; 10];
    for i in 0..4 {
        shape[i] = l[i] * (2. * l[i] - 1.);
        for a in 0..3 {
            gradient[i][a] = (4. * l[i] - 1.) * g[i][a];
        }
    }
    for (k, [i, j]) in EDGES.into_iter().enumerate() {
        shape[k + 4] = 4. * l[i] * l[j];
        for a in 0..3 {
            gradient[k + 4][a] = 4. * (l[i] * g[j][a] + l[j] * g[i][a]);
        }
    }
    (shape, gradient)
}
fn mapping(
    points: &[[f64; 3]],
    r: [f64; 3],
) -> ([f64; 10], [[f64; 3]; 10], Vector3<f64>, Matrix3<f64>) {
    let (shape, gradient) = tet10_shape(r);
    let origin = Vector3::from_row_slice(&points[0]);
    let mut x = origin;
    let mut j = Matrix3::zeros();
    for i in 0..10 {
        let offset = Vector3::from_row_slice(&points[i]) - origin;
        x += offset * shape[i];
        for a in 0..3 {
            for b in 0..3 {
                j[(a, b)] += offset[a] * gradient[i][b];
            }
        }
    }
    (shape, gradient, x, j)
}

fn multiindices() -> Vec<[usize; 4]> {
    let mut result = Vec::new();
    for a in 0..=3 {
        for b in 0..=3 - a {
            for c in 0..=3 - a - b {
                result.push([a, b, c, 3 - a - b - c]);
            }
        }
    }
    result
}
fn bernstein(l: [f64; 4], powers: [usize; 4]) -> f64 {
    let factorial = [1., 1., 2., 6.];
    let coefficient = 6. / powers.iter().map(|&p| factorial[p]).product::<f64>();
    coefficient * (0..4).map(|i| l[i].powi(powers[i] as i32)).product::<f64>()
}
/// det(J) is a cubic polynomial. Positive Bernstein coefficients give a
/// sufficient positivity bound on a reference sub-tetrahedron.
pub fn certify_tet10(points: &[[f64; 3]]) -> Result<()> {
    if points.len() != 10 || !points.iter().flatten().all(|x| x.is_finite()) {
        return Err(Error::Input("Tet10 requires ten finite points".into()));
    }
    let corners: [[_; 3]; 4] = std::array::from_fn(|i| points[i]);
    crate::mesh::geometry(&corners)?;
    let scale = points
        .iter()
        .flat_map(|a| {
            points
                .iter()
                .map(move |b| (Vector3::from_row_slice(a) - Vector3::from_row_slice(b)).norm())
        })
        .fold(0., f64::max);
    let threshold = 1e-12 * scale.powi(3);
    let indices = multiindices();
    static INVERSE: OnceLock<Option<SMatrix<f64, 20, 20>>> = OnceLock::new();
    let inverse = INVERSE
        .get_or_init(|| {
            let mut v = SMatrix::<f64, 20, 20>::zeros();
            for (i, p) in indices.iter().enumerate() {
                let l = p.map(|a| a as f64 / 3.);
                for (j, &powers) in indices.iter().enumerate() {
                    v[(i, j)] = bernstein(l, powers);
                }
            }
            v.try_inverse()
        })
        .as_ref()
        .ok_or_else(|| Error::Input("Bernstein interpolation matrix is singular".into()))?;
    let root = [[0., 0., 0.], [1., 0., 0.], [0., 1., 0.], [0., 0., 1.]];
    let mut pending = vec![(root, 0)];
    let mut count = 0;
    while let Some((cell, depth)) = pending.pop() {
        count += 1;
        if count > 4096 {
            return Err(Error::Input(
                "Tet10 Jacobian certification budget exceeded".into(),
            ));
        }
        let mut values = SVector::<f64, 20>::zeros();
        for (k, p) in indices.iter().enumerate() {
            let r = std::array::from_fn(|a| (0..4).map(|i| cell[i][a] * p[i] as f64 / 3.).sum());
            let determinant = mapping(points, r).3.determinant();
            if !determinant.is_finite() || determinant <= threshold {
                return Err(Error::Input("inverted/near-singular Tet10 Jacobian".into()));
            }
            values[k] = determinant;
        }
        let coefficients = inverse * values;
        let roundoff =
            100. * f64::EPSILON * coefficients.iter().map(|x| x.abs()).fold(0., f64::max);
        if coefficients.min() > threshold + roundoff {
            continue;
        }
        if depth >= 7 {
            return Err(Error::Input(
                "Tet10 Jacobian positivity could not be certified".into(),
            ));
        }
        let center = std::array::from_fn(|a| cell.iter().map(|p| p[a]).sum::<f64>() / 4.);
        for opposite in 0..4 {
            let mut child = cell;
            child[opposite] = center;
            pending.push((child, depth + 1));
        }
    }
    Ok(())
}

/// Isoparametric position and Jacobian. Callers still certify the whole cell.
pub fn tet_mapping(points: &[[f64; 3]], r: [f64; 3]) -> Result<([f64; 3], Matrix3<f64>)> {
    if ![4, 10].contains(&points.len())
        || !points
            .iter()
            .flatten()
            .chain(r.iter())
            .all(|v| v.is_finite())
    {
        return Err(Error::Input(
            "tetrahedron mapping requires finite Tet4/Tet10 coordinates".into(),
        ));
    }
    let (x, j) = if points.len() == 10 {
        let (_, _, x, j) = mapping(points, r);
        (x, j)
    } else {
        let p = points.iter().map(|p| Vector3::from(*p)).collect::<Vec<_>>();
        let j = Matrix3::from_columns(&[p[1] - p[0], p[2] - p[0], p[3] - p[0]]);
        (p[0] + j * Vector3::from(r), j)
    };
    if !j.iter().chain(x.iter()).all(|v| v.is_finite())
        || !j.determinant().is_finite()
        || j.determinant() <= 0.
    {
        return Err(Error::Input(
            "invalid isoparametric tetrahedron mapping".into(),
        ));
    }
    Ok((x.into(), j))
}

pub fn volume_points(points: &[[f64; 3]], order: usize) -> Result<Vec<VolumePoint>> {
    if points.len() == 4 {
        let corners = std::array::from_fn(|i| points[i]);
        let d = elastic::constitutive(1., 0.25)?;
        let (weight, b, _) = elastic::element(&corners, &d)?;
        return Ok(vec![VolumePoint {
            natural: [0.25; 3],
            position: std::array::from_fn(|a| points.iter().map(|p| p[a]).sum::<f64>() / 4.),
            weight_m3: weight,
            shape: vec![0.25; 4],
            b: DMatrix::from_column_slice(6, 12, b.as_slice()),
        }]);
    }
    certify_tet10(points)?;
    let mut result = Vec::new();
    for &(r, w) in volume_rule(order)? {
        let (shape, gradient, x, j) = mapping(points, r);
        let determinant = j.determinant();
        let inverse = j
            .try_inverse()
            .ok_or_else(|| Error::Input("singular Tet10 Jacobian".into()))?;
        let mut b = DMatrix::zeros(6, 30);
        for (i, g) in gradient.iter().enumerate() {
            let g = inverse.transpose() * Vector3::from_row_slice(g);
            let k = 3 * i;
            b[(0, k)] = g.x;
            b[(1, k + 1)] = g.y;
            b[(2, k + 2)] = g.z;
            b[(3, k)] = g.y;
            b[(3, k + 1)] = g.x;
            b[(4, k + 1)] = g.z;
            b[(4, k + 2)] = g.y;
            b[(5, k)] = g.z;
            b[(5, k + 2)] = g.x;
        }
        result.push(VolumePoint {
            natural: r,
            position: x.into(),
            weight_m3: w * determinant,
            shape: shape.to_vec(),
            b,
        });
    }
    Ok(result)
}

/// Scalar H1 basis on an already validated tetrahedron, also at face points.
pub fn scalar_gradient(points: &[[f64; 3]], r: [f64; 3]) -> Result<Vec<[f64; 3]>> {
    if points.len() == 4 {
        return Ok(crate::mesh::geometry(&std::array::from_fn(|i| points[i]))?
            .1
            .map(Into::into)
            .to_vec());
    }
    if points.len() != 10 {
        return Err(Error::Input("scalar basis requires Tet4/Tet10".into()));
    }
    let (_, g, _, j) = mapping(points, r);
    let inverse = j
        .try_inverse()
        .ok_or_else(|| Error::Input("singular scalar isoparametric Jacobian".into()))?;
    if !j.determinant().is_finite() || j.determinant() <= 0. {
        return Err(Error::Input("invalid scalar isoparametric Jacobian".into()));
    }
    Ok(g.into_iter()
        .map(|v| (inverse.transpose() * Vector3::from(v)).into())
        .collect())
}

pub(crate) fn tri_shape(r: [f64; 2], quadratic: bool) -> (Vec<f64>, Vec<[f64; 2]>) {
    let l = [1. - r[0] - r[1], r[0], r[1]];
    let g = [[-1., -1.], [1., 0.], [0., 1.]];
    if !quadratic {
        return (l.to_vec(), g.to_vec());
    }
    let mut shape = vec![0.; 6];
    let mut gradient = vec![[0.; 2]; 6];
    for i in 0..3 {
        shape[i] = l[i] * (2. * l[i] - 1.);
        for a in 0..2 {
            gradient[i][a] = (4. * l[i] - 1.) * g[i][a];
        }
    }
    for (k, [i, j]) in [[0, 1], [1, 2], [2, 0]].into_iter().enumerate() {
        shape[k + 3] = 4. * l[i] * l[j];
        for a in 0..2 {
            gradient[k + 3][a] = 4. * (l[i] * g[j][a] + l[j] * g[i][a]);
        }
    }
    (shape, gradient)
}
pub fn face_points(points: &[[f64; 3]]) -> Result<Vec<FacePoint>> {
    face_points_order(points, 4)
}

pub fn face_points_order(points: &[[f64; 3]], order: usize) -> Result<Vec<FacePoint>> {
    if !(2..=24).contains(&order) {
        return Err(Error::Input("invalid surface quadrature order".into()));
    }
    if ![3, 6].contains(&points.len()) || !points.iter().flatten().all(|p| p.is_finite()) {
        return Err(Error::Input("surface needs three/six finite nodes".into()));
    }
    let rule: Vec<([f64; 2], f64)> = if points.len() == 3 {
        vec![
            ([1. / 6., 1. / 6.], 1. / 6.),
            ([2. / 3., 1. / 6.], 1. / 6.),
            ([1. / 6., 2. / 3.], 1. / 6.),
        ]
    } else {
        let a = gauss(order, 1.);
        let b = gauss(order, 0.);
        let mut q = Vec::new();
        for &(u, wu) in &a {
            for &(v, wv) in &b {
                q.push(([u, (1. - u) * v], wu * wv));
            }
        }
        q
    };
    let mut result = Vec::new();
    let origin = Vector3::from_row_slice(&points[0]);
    for (r, w) in rule {
        let (shape, gradient) = tri_shape(r, points.len() == 6);
        let mut x = origin;
        let mut du = Vector3::zeros();
        let mut dv = Vector3::zeros();
        for i in 0..points.len() {
            let offset = Vector3::from_row_slice(&points[i]) - origin;
            x += offset * shape[i];
            du += offset * gradient[i][0];
            dv += offset * gradient[i][1];
        }
        let normal = du.cross(&dv) * w;
        if !normal.iter().all(|x| x.is_finite()) || normal.norm() <= f64::MIN_POSITIVE {
            return Err(Error::Input("degenerate surface Jacobian".into()));
        }
        result.push(FacePoint {
            position: x.into(),
            area_vector: normal.into(),
            shape,
        });
    }
    Ok(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    fn unit() -> Vec<[f64; 3]> {
        let mut p = vec![[0., 0., 0.], [1., 0., 0.], [0., 1., 0.], [0., 0., 1.]];
        for [i, j] in EDGES {
            p.push(std::array::from_fn(|a| (p[i][a] + p[j][a]) / 2.));
        }
        p
    }
    #[test]
    fn positive_quadrature_integrates_all_degree_five_monomials() -> Result<()> {
        fn factorial(n: usize) -> f64 {
            (1..=n).map(|i| i as f64).product()
        }
        for a in 0..=5 {
            for b in 0..=5 - a {
                for c in 0..=5 - a - b {
                    let expected =
                        factorial(a) * factorial(b) * factorial(c) / factorial(a + b + c + 3);
                    let computed: f64 = volume_rule(3)?
                        .iter()
                        .map(|(r, w)| {
                            r[0].powi(a as i32) * r[1].powi(b as i32) * r[2].powi(c as i32) * w
                        })
                        .sum();
                    assert!((computed - expected).abs() < 2e-15);
                }
            }
        }
        assert!(volume_rule(3)?.iter().all(|(_, w)| *w > 0.));
        Ok(())
    }
    #[test]
    fn tet10_partition_affine_patch_and_six_rigid_modes() -> Result<()> {
        let points = unit();
        let quadrature = volume_points(&points, 3)?;
        let strain = SVector::<f64, 6>::from_row_slice(&[0.01, -0.03, 0.04, 0.02, 0., 0.]);
        for q in quadrature {
            assert!((q.shape.iter().sum::<f64>() - 1.).abs() < 1e-14);
            let u = nalgebra::DVector::from_fn(30, |i, _| {
                let p = points[i / 3];
                match i % 3 {
                    0 => 0.01 * p[0] + 0.02 * p[1],
                    1 => -0.03 * p[1],
                    _ => 0.04 * p[2],
                }
            });
            assert!((&q.b * u - strain).norm() < 1e-14);
            for axis in 0..3 {
                let translation = nalgebra::DVector::from_fn(30, |i, _| f64::from(i % 3 == axis));
                assert!((&q.b * translation).norm() < 1e-14);
                let rotation = nalgebra::DVector::from_fn(30, |i, _| {
                    let mut a = Vector3::zeros();
                    a[axis] = 1.;
                    a.cross(&Vector3::from_row_slice(&points[i / 3]))[i % 3]
                });
                assert!((&q.b * rotation).norm() < 1e-14);
            }
        }
        Ok(())
    }
    #[test]
    fn jacobian_certificate_rejects_fold_outside_integration_points() -> Result<()> {
        let mut points = unit();
        points[4][0] = 0.24;
        assert!(
            volume_rule(3)?
                .iter()
                .all(|(r, _)| mapping(&points, *r).3.determinant() > 0.)
        );
        assert!(certify_tet10(&points).is_err());
        let mut curved = unit();
        curved[4][1] = 0.03;
        certify_tet10(&curved)?;
        assert!(volume_points(&curved, 3)?.iter().all(|q| q.weight_m3 > 0.));
        Ok(())
    }
    #[test]
    fn tri6_integrates_constant_traction_and_linear_pressure() -> Result<()> {
        let p = vec![
            [0., 0., 0.],
            [1., 0., 0.],
            [0., 1., 0.],
            [0.5, 0., 0.],
            [0.5, 0.5, 0.],
            [0., 0.5, 0.],
        ];
        let q = face_points(&p)?;
        let mut f = [0.; 6];
        for point in &q {
            for (i, fi) in f.iter_mut().enumerate() {
                *fi += point.shape[i] * (1. + point.position[0]) * point.area_vector[2];
            }
        }
        assert!((f.iter().sum::<f64>() - 2. / 3.).abs() < 1e-14);
        assert!((f[0] + 1. / 120.).abs() < 1e-14);
        assert!(f[3..].iter().all(|x| *x > 0.));
        Ok(())
    }
}
